#!/usr/bin/env bash
# ==============================================================================
# FoodCourt & Pakwan — Unified One-Command Auto Deployment & Verification Suite
# ==============================================================================
# Usage:
#   ./deploy/deploy.sh "Your commit message"
#   npm run deploy
#   bash deploy/deploy.sh
# ==============================================================================

set -e

# ANSI Color Codes
GREEN="\033[1;32m"
RED="\033[1;31m"
YELLOW="\033[1;33m"
CYAN="\033[1;36m"
BLUE="\033[1;34m"
PURPLE="\033[1;35m"
BOLD="\033[1m"
RESET="\033[0m"

# Project Root Directory
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo -e "\n${BOLD}${CYAN}======================================================${RESET}"
echo -e "${BOLD}${CYAN} 🚀 FoodCourt & Pakwan — Automated Deployment Pipeline ${RESET}"
echo -e "${BOLD}${CYAN}======================================================${RESET}"
echo -e "${BLUE}Working Directory:${RESET} $REPO_ROOT"
echo -e "${BLUE}Timestamp:${RESET} $(date '+%Y-%m-%d %H:%M:%S')"

# ------------------------------------------------------------------------------
# STEP 1: PRE-FLIGHT SYNTAX & INTEGRITY CHECKS
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${YELLOW}[1/5] Running Pre-Flight Syntax & Integrity Checks...${RESET}"

SYNTAX_ERRORS=0
if command -v php &>/dev/null; then
    echo -e "  🔍 Checking PHP syntax across php-backend/..."
    while IFS= read -r -d '' php_file; do
        ERR_MSG=$(php -l "$php_file" 2>&1)
        if [ $? -ne 0 ]; then
            echo -e "  ${RED}❌ Syntax Error in: $php_file${RESET}"
            echo -e "     $ERR_MSG"
            SYNTAX_ERRORS=$((SYNTAX_ERRORS + 1))
        fi
    done < <(find php-backend/ -type f -name "*.php" -print0)

    if [ "$SYNTAX_ERRORS" -gt 0 ]; then
        echo -e "\n${RED}🛑 Deployment ABORTED: $SYNTAX_ERRORS fatal PHP syntax error(s) found!${RESET}"
        echo -e "${YELLOW}Please fix code errors before deploying to live server.${RESET}"
        exit 1
    fi
    echo -e "  ${GREEN}✓ All PHP files passed syntax validation (Zero errors)${RESET}"
else
    echo -e "  ${YELLOW}⚠ PHP CLI not found locally, skipping php -l checks.${RESET}"
fi

# Verify SQLite database file exists
if [ -f "php-backend/data/foodcourt.sqlite" ]; then
    DB_SIZE=$(du -h "php-backend/data/foodcourt.sqlite" | awk '{print $1}')
    echo -e "  ${GREEN}✓ SQLite database verified (Size: $DB_SIZE)${RESET}"
else
    echo -e "  ${YELLOW}⚠ php-backend/data/foodcourt.sqlite not found (will be generated by runtime)${RESET}"
fi

# ------------------------------------------------------------------------------
# STEP 2: BUILD OFFLINE DEPLOYMENT ZIP (HOSTINGER / CPANEL FALLBACK)
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${YELLOW}[2/5] Updating Standalone Hosting Deployment Package...${RESET}"

if command -v zip &>/dev/null; then
    (cd php-backend && zip -q -r -FS ../php-backend-deploy.zip . -x "*.DS_Store" -x "uploads/*.apk")
    ZIP_SIZE=$(du -h php-backend-deploy.zip | awk '{print $1}')
    echo -e "  ${GREEN}✓ Updated php-backend-deploy.zip ($ZIP_SIZE) for 1-click manual upload${RESET}"
else
    echo -e "  ${YELLOW}⚠ zip utility not installed, skipping zip update.${RESET}"
fi

# ------------------------------------------------------------------------------
# STEP 3: GIT STAGING, COMMIT & PUSH TO PRODUCTION REPO
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${YELLOW}[3/5] Syncing to Git Remote Repository...${RESET}"

COMMIT_MSG="$1"
if [ -z "$COMMIT_MSG" ]; then
    COMMIT_MSG="Auto-deploy updates: $(date '+%Y-%m-%d %H:%M:%S')"
fi

# Stage all relevant modifications
git add -A

# Check if there are changes to commit
if git diff-index --quiet HEAD --; then
    echo -e "  ${CYAN}ℹ Working tree clean (no new unstaged changes). Checking remote status...${RESET}"
else
    git commit -m "$COMMIT_MSG"
    echo -e "  ${GREEN}✓ Committed changes:${RESET} $COMMIT_MSG"
fi

# Push to origin main
echo -e "  🚀 Pushing to remote repository (origin main)..."
if git push origin main; then
    CURRENT_COMMIT=$(git rev-parse --short HEAD)
    echo -e "  ${GREEN}✓ Successfully pushed commit [${CURRENT_COMMIT}] to origin/main${RESET}"
else
    echo -e "  ${RED}❌ Git push failed! Please check git credentials / network connectivity.${RESET}"
    exit 1
fi

# ------------------------------------------------------------------------------
# STEP 4: DIRECT SERVER UPLOAD (OPTIONAL SSH / FTP SYNC IF CONFIGURED)
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${YELLOW}[4/5] Checking Direct Server Sync Configuration...${RESET}"

ENV_DEPLOY_FILE="$REPO_ROOT/deploy/.env.deploy"
if [ -f "$ENV_DEPLOY_FILE" ]; then
    # Load configuration
    set -a
    source "$ENV_DEPLOY_FILE"
    set +a

    if [ -n "$DEPLOY_SSH_HOST" ] && [ -n "$DEPLOY_SSH_USER" ] && [ -n "$DEPLOY_SSH_REMOTE_PATH" ]; then
        echo -e "  📡 Running direct SSH/Rsync sync to ${DEPLOY_SSH_USER}@${DEPLOY_SSH_HOST}..."
        SSH_PORT="${DEPLOY_SSH_PORT:-22}"
        rsync -avz -e "ssh -p $SSH_PORT" --exclude '.git' --exclude 'data/foodcourt.sqlite' php-backend/ "${DEPLOY_SSH_USER}@${DEPLOY_SSH_HOST}:${DEPLOY_SSH_REMOTE_PATH}/"
        echo -e "  ${GREEN}✓ Direct SSH sync completed!${RESET}"

        # Clear PHP OPcache on server to immediately reflect changes
        echo -e "  🔄 Flushing PHP OPcache on server..."
        ssh -p "$SSH_PORT" "${DEPLOY_SSH_USER}@${DEPLOY_SSH_HOST}" \
            "echo '<?php if(function_exists(\"opcache_reset\")){ opcache_reset(); echo \"OPCACHE_RESET_OK\"; } unlink(__FILE__); ?>' > ${DEPLOY_SSH_REMOTE_PATH}/opcache_clear.php && curl -s https://${DEPLOY_SSH_HOST}/opcache_clear.php > /dev/null 2>&1"
        echo -e "  ${GREEN}✓ Remote PHP OPcache flushed successfully!${RESET}"
    elif [ -n "$DEPLOY_FTP_HOST" ] && [ -n "$DEPLOY_FTP_USER" ]; then
        echo -e "  📡 Direct FTP credentials detected. (Using FTP transfer if lftp/curl is installed)..."
        # Optional FTP logic
    else
        echo -e "  ${CYAN}ℹ .env.deploy present but no active credentials. Using GitHub Auto-Deploy Webhook.${RESET}"
    fi
else
    echo -e "  ${CYAN}ℹ No .env.deploy found. Using standard Git Deployment (Hostinger Webhook / Auto-Deploy).${RESET}"
    echo -e "  ${CYAN}  (To enable direct SSH/SFTP sync, copy deploy/.env.deploy.example to deploy/.env.deploy)${RESET}"
fi

# ------------------------------------------------------------------------------
# STEP 5: LIVE SERVER HEALTH CHECK & VERIFICATION
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${YELLOW}[5/5] Performing Real-Time Live Server Health Checks...${RESET}"

ENDPOINTS=(
    "https://food.aztemp.com/|Live Home / Hub Landing"
    "https://food.aztemp.com/vendor/login.php|Vendor Portal (Auth & Management)"
    "https://food.aztemp.com/admin/login.php|Sub-Admin / Store Manager Login"
    "https://food.aztemp.com/api/dashboard/stats|REST API Live Endpoint"
)

ALL_HEALTHY=true

for item in "${ENDPOINTS[@]}"; do
    URL="${item%%|*}"
    NAME="${item##*|}"

    HTTP_CODE=$(curl -s -o /dev/null -w "%{http_code}" --connect-timeout 8 --max-time 12 "$URL" || echo "FAILED")
    TIME_TOTAL=$(curl -s -o /dev/null -w "%{time_total}" --connect-timeout 8 --max-time 12 "$URL" || echo "0")

    if [ "$HTTP_CODE" = "200" ] || [ "$HTTP_CODE" = "302" ] || [ "$HTTP_CODE" = "301" ]; then
        echo -e "  ${GREEN}✔ [HTTP $HTTP_CODE]${RESET} $NAME (${TIME_TOTAL}s) \n     ${BLUE}URL:${RESET} $URL"
    else
        echo -e "  ${RED}✖ [HTTP $HTTP_CODE]${RESET} $NAME (${TIME_TOTAL}s) \n     ${RED}URL:${RESET} $URL (Potential Glitch/Issue)"
        ALL_HEALTHY=false
    fi
done

# ------------------------------------------------------------------------------
# SUMMARY & FINAL STATUS REPORT
# ------------------------------------------------------------------------------
echo -e "\n${BOLD}${CYAN}======================================================${RESET}"
if [ "$ALL_HEALTHY" = true ]; then
    echo -e "${BOLD}${GREEN} 🎉 DEPLOYMENT SUCCESSFUL! All Endpoints Live & Healthy ${RESET}"
    echo -e "${BOLD}${CYAN}======================================================${RESET}"
    echo -e "${GREEN}✓ Status:${RESET} Live on Production (${CURRENT_COMMIT})"
    echo -e "${GREEN}✓ Vendor Portal:${RESET} https://food.aztemp.com/vendor/login.php"
    echo -e "${GREEN}✓ Admin Portal:${RESET}  https://food.aztemp.com/admin/login.php"
    echo -e "${GREEN}✓ API Service:${RESET}   https://food.aztemp.com/api/"
    echo -e "${GREEN}✓ Offline Zip:${RESET}   $REPO_ROOT/php-backend-deploy.zip"
    echo -e "\n${BOLD}${PURPLE}You can now test the latest changes directly on the live site!${RESET}\n"
    exit 0
else
    echo -e "${BOLD}${YELLOW} ⚠ DEPLOYMENT FINISHED WITH HEALTH WARNINGS ${RESET}"
    echo -e "${BOLD}${CYAN}======================================================${RESET}"
    echo -e "${YELLOW}Code was pushed to GitHub. However, one or more endpoints returned an unexpected status code.${RESET}"
    echo -e "${YELLOW}Please review the health check outputs above.${RESET}\n"
    exit 0
fi
